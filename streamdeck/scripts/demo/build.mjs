// Builds the plugin for the browser demo on the public support site.
//
// The plugin's own source is bundled unchanged. Only the Stream Deck SDK and the parts that need
// Node or the network are swapped for stand-ins (see REPLACE), so the keys in the demo are drawn
// and driven by the same code as the real plugin.
//
//   npm run demo:build             -> dist/demo/plugin.js
//   npm run demo:build -- <dir>    -> <dir>/plugin.js (e.g. the support repo's demo folder)
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const out = path.resolve(process.argv[2] ?? path.join(root, "dist/demo"), "plugin.js");

/** Module -> stand-in. Keys are package names, or source paths relative to the repo (no extension). */
const REPLACE = {
	"@elgato/streamdeck": "scripts/demo/sdk-shim.ts",
	// Nothing else: the poller uses fetch(), which the demo page answers with a pretend server.
};

const byPath = new Map(
	Object.entries(REPLACE)
		.filter(([k]) => k.startsWith("src/") || k.startsWith("node:"))
		.map(([k, v]) => [k.startsWith("node:") ? k : path.join(root, k), path.join(root, v)]),
);

const swap = {
	name: "demo-swap",
	setup(b) {
		b.onResolve({ filter: /.*/ }, (args) => {
			if (REPLACE[args.path] && !args.path.startsWith("src/")) return { path: path.join(root, REPLACE[args.path]) };
			if (args.path.startsWith(".") && args.importer) {
				const abs = path.resolve(path.dirname(args.importer), args.path).replace(/\.(js|ts)$/, "");
				if (byPath.has(abs)) return { path: byPath.get(abs) };
			}
			return undefined;
		});
	},
};

await build({
	entryPoints: [path.join(here, "entry.ts")],
	bundle: true,
	format: "esm",
	platform: "browser",
	target: "es2022",
	minify: true,
	legalComments: "none",
	inject: [path.join(here, "node-globals.ts")],
	plugins: [swap],
	outfile: out,
	banner: { js: "// Generated by scripts/demo/build.mjs from the plugin's source. Do not edit." },
});
console.log(`demo bundle -> ${path.relative(process.cwd(), out)}`);
